#!/usr/bin/env python3
"""Writes the JS data file the browser patcher needs (globalThis.Nova43Data) from patch.py.
  python3 tools/gen_web_data.py <out.js>
"""
import base64
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import patch  # noqa: E402


def b64(b):
    return base64.b64encode(b).decode("ascii")


def main():
    if len(sys.argv) != 2:
        print("usage: gen_web_data.py <out.js>", file=sys.stderr)
        return 2
    data = {
        "version": patch.PATCH_VERSION,
        "block": b64(patch.block_bytes()),
        "knownVanilla": dict(patch.KNOWN_VANILLA),
        "begin": b64(patch.BEGIN),
        "end": b64(patch.END),
    }
    out = "/* generated by tools/gen_web_data.py from patch.py and patch/nova43.lua; do not edit */\nglobalThis.Nova43Data = " + json.dumps(data, indent=2) + ";\n"
    with open(sys.argv[1], "w", newline="\n") as f:
        f.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
